        db.row_factory = aiosqlite.Row
        placeholders = ",".join("?" for _ in _BOOKABLE_STATUSES)
        tour = await (await db.execute(
            f"SELECT * FROM tours WHERE id=? AND status IN ({placeholders})", (tid, *_BOOKABLE_STATUSES),
        )).fetchone()
