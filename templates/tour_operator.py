    if config.welcome_image.exists():
        await m.answer_photo(FSInputFile(str(config.welcome_image)), caption=text,
                             parse_mode="HTML", reply_markup=kb)
    else:
        await m.answer(text, parse_mode="HTML", reply_markup=kb)

