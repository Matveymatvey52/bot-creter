# ── config (Stage 2 Phase 7) ─────────────────────────────────────────────────
# Same pattern as templates/accountant.py (Phase 2), manager_secretary.py
# (Phase 4), booking_beauty.py (Phase 5) and trip_manager.py (Phase 6) — see
# docs/STAGE2_DESIGN.md "Фаза 7". display_name/group_chat_id are decorative
# here (verified: no matches) — this template has no group-chat feature.
#
# The web CRM part (build_web_app()/serve_app()/REST API below) is translated
# onto config too, for structural uniformity with the rest of the file, but per
# the owner's decision it is NOT started by runtime/registry.py in webhook mode
# — see docs/STAGE2_DESIGN.md "Стоп: веб-часть не ложится на паттерн" for why
# (the webhook runtime already binds one aiohttp server on the same PORT; a
# second one per bot would collide). main() (standalone) is unchanged — it
# still starts the web server exactly as before.

@dataclass
class TourOperatorConfig:
    bot_name: str
    db_path: str
    admins_file: str  # plain str (not Path) — matches this template's original
                       # os.path.exists()/open() style, unchanged behavior
    welcome_image: Path
    display_name: str | None = None   # not used by this template (verified: no matches)
    group_chat_id: str | None = None  # not used by this template (verified: no matches)
    # Only set in webhook mode (config_from_bot_row) — standalone mode has no
    # bots-table row to source it from, same as display_name/group_chat_id
    # above. Used by _miniapp_url() to scope a magic-link token to this bot;
    # None in standalone mode simply means no mini-app link can be minted
    # there (WEB_CRM_ENABLED's own standalone web server doesn't need one).
    bot_id: int | None = None
    # Only set in webhook mode. The sole user allowed to claim the empty-
    # admins bootstrap slot at /start, and always treated as admin by
    # _is_admin() regardless of admins_file state — see _is_admin's docstring.
    owner_telegram_id: int | None = None


def _paths_for(name: str, data_dir: Path) -> TourOperatorConfig:
    return TourOperatorConfig(
        bot_name=name,
        db_path=str(data_dir / f"{name}.db"),
        admins_file=str(data_dir / f"admins_{name}.json"),
        welcome_image=data_dir / "bot_images" / f"{name}.jpg",
    )


def config_from_env() -> TourOperatorConfig:
    """Standalone/subprocess mode: reproduces exactly what the old module-level
    constants gave, behavior unchanged 1:1."""
    name = Path(__file__).stem
    data_dir = Path(os.getenv("DATA_DIR", "./data"))
    data_dir.mkdir(exist_ok=True)
    return _paths_for(name, data_dir)


def config_from_bot_row(bot_row: dict, data_dir: Path) -> TourOperatorConfig:
    """Webhook runtime mode (Telegram handlers only — see module docstring
    above). `data_dir` is a required caller-supplied param — same reasoning as
    every other migrated template's config_from_bot_row.

    Paths are built from bot_row["bot_id"] (bots.id, the physically unique
    AUTOINCREMENT PK) — NOT bot_row["name"], which has no UNIQUE constraint
    and would otherwise let two same-named bots silently share one db/admins
    file (see docs/STAGE2_DESIGN.md "Изоляция по bots.id"). bot_row["name"] is
    kept only as the human-readable bot_name label, never used in a path.
    Deliberately does NOT reuse _paths_for()/config_from_env()'s name-based
    formula — that stays untouched for standalone mode, where bot_id doesn't
    exist (one process = one bot, no collision possible). admins_file stays a
    plain str here (this template's own file-handling style, unrelated to
    isolation), just built from bot_id like everything else; db_path now gets
    the same "_data" suffix as the other four templates (this template's own
    historic naming quirk is dropped along with the switch to id — old data
    is being discarded regardless, so there's no reason to preserve it)."""
    bot_id = bot_row["bot_id"]
    config = TourOperatorConfig(
        bot_name=bot_row["name"],
        db_path=str(data_dir / f"bot_{bot_id}_data.db"),
        admins_file=str(data_dir / f"admins_{bot_id}.json"),
        welcome_image=data_dir / "bot_images" / f"bot_{bot_id}.jpg",
    )
    config.display_name = bot_row.get("display_name")
    config.group_chat_id = bot_row.get("group_chat_id")
    config.bot_id = bot_id
    config.owner_telegram_id = bot_row.get("owner_telegram_id")
    # Registers this bot's voice-intake schema NOW, since bot_id is only
    # known from this point on (init_db(db_path) below has no bot_id at
    # all — see runtime/registry.py's _build_generic_middleware, which calls
    # config_from_bot_row BEFORE init_db). Idempotent — see
    # voice_intake.register_schema's own docstring for why re-registering on
    # every reload_one/reload_all is safe.
    voice_intake.register_schema(bot_id, _build_voice_schema())
    return config


class ConfigMiddleware(BaseMiddleware):
    """Injects this bot's TourOperatorConfig into every handler's `data["config"]`.
    Defined here (not imported from runtime/) so this file stays self-contained —
    same invariant as every other templates/*.py: no project-internal imports."""

    def __init__(self, config: TourOperatorConfig) -> None:
        self.config = config
        super().__init__()

    async def __call__(self, handler, event, data):
        data["config"] = self.config
        return await handler(event, data)


# ── Admin ─────────────────────────────────────────────────────────────────────
def _load_admins(admins_file: str):
    if not os.path.exists(admins_file):
        return []
    try:
        with open(admins_file) as f:
            data = json.load(f)
        # db.database.sync_bot_admins_json (webhook mode — used by both the
        # normal /create flow and any DB-side bot provisioning) writes
        # {"ids": [...]} with string ids, not a bare list of ints. Standalone
        # mode's _save_admins below writes the same {"ids": [...]} shape now
        # too, so both modes agree on one format.
        if isinstance(data, dict):
            return data.get("ids", [])
        return data
    except Exception:
        return []

def _save_admins(admins_file: str, lst):
    with open(admins_file, "w") as f:
        json.dump({"ids": [str(x) for x in lst]}, f)

def _is_admin(uid, config: "TourOperatorConfig"):
    # DB-known owner (bots.owner_telegram_id) is always admin, even if the
    # local admins_file is empty/stale — mirrors shop_catalog.py's
    # _is_bot_admin. Bug fixed here: this used to bootstrap admins_file with
    # `uid` on EVERY call whenever the admins list was empty (not just at
    # /start), so removing the last admin via any future /removeadmin-style
    # flow let the next caller of ANY admin-gated command silently become the
    # new admin. A rights check must never grant admin as a side effect of
    # being called — bootstrap is now only done once, explicitly, in
    # cmd_start below.
    if config.owner_telegram_id is not None and str(uid) == str(config.owner_telegram_id):
        return True
    return str(uid) in _load_admins(config.admins_file)

def _esc(value, max_len: int = 500) -> str:
    """HTML-escapes AND length-bounds any user-supplied text before it goes
    into a parse_mode="HTML" message — same helper/rationale as templates/
    property_rental.py's _esc()."""
    text = str(value) if value is not None else ""
    if len(text) > max_len:
        text = text[:max_len] + "…"
    return html.escape(text)

